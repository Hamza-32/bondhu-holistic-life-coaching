/**
 * Generates the reference-data seed files from the verified research data in supabase/data/.
 *
 *   supabase/data/*.json   verified data with sources and verbatim evidence (see docs/DATA_SOURCES.md)
 *   supabase/data/overrides.json   curated edits: Bangla translations, normalised hours, exclusions
 *
 * Only entries marked VERIFIED are seeded. Output is idempotent (upserts on natural keys).
 * Usage: npm run db:seed:build
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const DATA = path.join(ROOT, 'supabase', 'data');
