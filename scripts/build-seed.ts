// 03 content: calendar, resources, careers (resources/careers appear once their data exists)
// ------------------------------------------------------------------------------------------------
const calendar = load<{ checked: string; events: Json[] }>('calendar.json');
const calendarRows = calendar.events
  .filter((e) => !overrides.calendar._skip_titles.includes(String(e.title_en)))
  .map((e) => {
    const titleBn = overrides.calendar.title_bn[String(e.title_en)] ?? e.title_bn;
    if (!titleBn) throw new Error(`Missing Bangla title for calendar event ${String(e.title_en)}`);
    return [
      e.kind,
      e.title_en,
      titleBn,
      e.starts_on,
      e.ends_on ?? null,
      e.is_approximate,
      e.source_url,
    ];
  });

let content =
  header('Content: cultural and academic calendar, resources, career paths', '') +
  `-- Calendar (${calendarRows.length} events), checked ${calendar.checked}\n` +
  upsert(
    'calendar_events',
    ['kind', 'title_en', 'title_bn', 'starts_on', 'ends_on', 'is_approximate', 'source_url'],
    calendarRows,
    '(kind, title_en, starts_on)',
    ['title_bn', 'ends_on', 'is_approximate', 'source_url'],
  ).replace(/'(\d{4}-\d{2}-\d{2})'/g, "'$1'::date");

