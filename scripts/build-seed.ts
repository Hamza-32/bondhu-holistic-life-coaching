type Json = Record<string, unknown>;

// eslint-disable-next-line @typescript-eslint/no-unnecessary-type-parameters -- typed JSON loader: each caller declares the shape it expects
function load<T>(file: string): T {
  return JSON.parse(readFileSync(path.join(DATA, file), 'utf8')) as T;
}

/** SQL literal for strings, numbers, booleans, null and text arrays. */
function lit(value: unknown): string {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'string') return `'${value.replace(/'/g, "''")}'`;
  if (Array.isArray(value)) {
    return value.length === 0 ? `'{}'::text[]` : `array[${value.map(lit).join(', ')}]::text[]`;
  }
  throw new Error(`Unsupported seed value: ${JSON.stringify(value)}`);
}

function row(values: unknown[]): string {
  return `  (${values.map(lit).join(', ')})`;
}

function upsert(
  table: string,
  columns: string[],
  rows: unknown[][],
  conflict: string,
  updateCols: string[],
) {
  if (rows.length === 0) return `-- ${table}: no verified rows yet\n`;
  const updates = updateCols.map((c) => `${c} = excluded.${c}`).join(', ');
  return `insert into public.${table} (${columns.join(', ')}) values\n${rows.map(row).join(',\n')}\non conflict ${conflict} do update set ${updates};\n`;
}

